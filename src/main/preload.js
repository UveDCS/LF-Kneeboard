// Puente seguro entre las páginas (kneeboard y ajustes) y el proceso principal.
const { contextBridge, ipcRenderer } = require('electron');

const arg = process.argv.find((a) => a.startsWith('--kb-view='));
const view = arg ? Number(arg.split('=')[1]) : -1;

const listen = (channel, cb) => {
  const fn = (e, ...args) => cb(...args);
  ipcRenderer.on(channel, fn);
  return () => ipcRenderer.removeListener(channel, fn);
};

contextBridge.exposeInMainWorld('kb', {
  view,
  init: () => ipcRenderer.invoke('init'),
  on: listen,
  patchConfig: (p) => ipcRenderer.invoke('config:patch', p),
  saveViewState: (state) => ipcRenderer.send('view:state', view, state),
  action: (a) => ipcRenderer.invoke('action', a),
  activate: () => ipcRenderer.invoke('view:activate', view),
  resize: (w) => ipcRenderer.send('view:resize', w),
  resizeDone: () => ipcRenderer.send('view:resizeDone'),
  setSize: (i, fraction) => ipcRenderer.send('view:setSize', i, fraction),
  coordsVisible: (on) => ipcRenderer.send('crosshair:coords', view, on),
  listFiles: (dir, kind) => ipcRenderer.invoke('fs:list', dir, kind),
  fileUrl: (p) => ipcRenderer.invoke('fs:url', p),
  thumb: (p) => ipcRenderer.invoke('fs:thumb', p),
  dcsKneeboard: (aircraft) => ipcRenderer.invoke('fs:dcsKneeboard', aircraft),
  kneeboardAll: (aircraft) => ipcRenderer.invoke('kneeboard:all', aircraft),
  openDialog: (opts) => ipcRenderer.invoke('dialog:open', opts),
  capture: () => ipcRenderer.invoke('coords:capture'),
  shareSend: (item) => ipcRenderer.invoke('share:send', item),
  sharePage: (title, data) => ipcRenderer.invoke('share:page', view, title, data),
  clearInbox: () => ipcRenderer.invoke('inbox:clear'),
  shareAddresses: () => ipcRenderer.invoke('share:addresses'),
  loadMiz: (file, unit) => ipcRenderer.invoke('mission:loadMiz', file, unit),
  selectUnit: (unit) => ipcRenderer.invoke('mission:selectUnit', unit),
  dtcList: () => ipcRenderer.invoke('dtc:list'),
  dtcRadios: (file) => ipcRenderer.invoke('dtc:radios', file),
  dtcImport: () => ipcRenderer.invoke('dtc:import'),
  dtcUse: (type, file) => ipcRenderer.invoke('dtc:use', type, file),
  dtcShare: () => ipcRenderer.invoke('dtc:share'),
  dtcInstallShared: (id) => ipcRenderer.invoke('dtc:installShared', id),
  bindCapture: (action) => ipcRenderer.invoke('bind:capture', action),
  bindCancel: () => ipcRenderer.invoke('bind:cancel'),
  bindDescribe: (combo) => ipcRenderer.invoke('bind:describe', combo),
  integrationStatus: () => ipcRenderer.invoke('integration:status'),
  integrationInstall: (what) => ipcRenderer.invoke('integration:install', what),
  integrationUninstall: (what) => ipcRenderer.invoke('integration:uninstall', what),
  recenter: () => ipcRenderer.invoke('vr:recenter'),
  vrOpenLog: () => ipcRenderer.invoke('vr:openlog'),
  timer: (cmd) => ipcRenderer.invoke('timer', cmd),
  messagesClear: () => ipcRenderer.invoke('messages:clear'),
  kneeboardProbe: () => ipcRenderer.invoke('dcs:kbprobe'),
  storeGet: (name) => ipcRenderer.invoke('store:get', name),
  storeSet: (name, data) => ipcRenderer.send('store:set', name, data),
  resetTabs: () => ipcRenderer.invoke('tabs:reset'),
  tabTemplates: () => ipcRenderer.invoke('tabs:templates'),
  applyTemplate: (id) => ipcRenderer.invoke('tabs:template', id),
  applyPreset: (id) => ipcRenderer.invoke('tabs:applyPreset', id),
  captureSources: () => ipcRenderer.invoke('capture:sources'),
  openSettings: (section) => ipcRenderer.invoke('app:settings', section),
  openExternal: (url) => ipcRenderer.invoke('app:external', url),
  focusDcs: () => ipcRenderer.invoke('app:focusDcs'),
  quit: () => ipcRenderer.invoke('app:quit'),
  library: {
    status: () => ipcRenderer.invoke('library:status'),
    detect: () => ipcRenderer.invoke('library:detect'),
    setRoot: (r) => ipcRenderer.invoke('library:setRoot', r),
    create: (name, ac) => ipcRenderer.invoke('library:create', name, ac),
    rename: (dir, name) => ipcRenderer.invoke('library:rename', dir, name),
    meta: (dir, p) => ipcRenderer.invoke('library:meta', dir, p),
    importFiles: (dir, files) => ipcRenderer.invoke('library:import', dir, files),
    savePages: (set, base, urls, opts) => ipcRenderer.invoke('library:savePages', set, base, urls, opts),
    pages: (ac) => ipcRenderer.invoke('library:pages', ac),
    apply: () => ipcRenderer.invoke('library:apply'),
    remove: () => ipcRenderer.invoke('library:remove'),
    inject: (miz, opts) => ipcRenderer.invoke('library:inject', miz, opts),
    trash: (dir) => ipcRenderer.invoke('library:trash', dir),
    trashFiles: (files) => ipcRenderer.invoke('library:trashFiles', files),
    open: (dir) => ipcRenderer.invoke('library:open', dir),
  },
  captureRect: (rect) => ipcRenderer.invoke('capture:rect', rect),
  courseGet: () => ipcRenderer.invoke('course:get'),
  courseLoad: (file) => ipcRenderer.invoke('course:load', file),
  logbook: () => ipcRenderer.invoke('logbook:get'),
  logbookClear: () => ipcRenderer.invoke('logbook:clear'),
  dtcAuto: (type) => ipcRenderer.invoke('dtc:auto', type),
  voiceStatus: () => ipcRenderer.invoke('voice:status'),
  update: {
    status: () => ipcRenderer.invoke('update:status'),
    check: () => ipcRenderer.invoke('update:check'),
    install: () => ipcRenderer.invoke('update:install'),
    now: () => ipcRenderer.invoke('update:now'),
  },
  profileExport: () => ipcRenderer.invoke('profile:export'),
  profileImport: () => ipcRenderer.invoke('profile:import'),
});
